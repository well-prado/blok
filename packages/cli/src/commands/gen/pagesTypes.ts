/** Modes whose prop may be absent from the page object on any given visit. */
const LAZY_MODES = new Set(["optional", "defer"]);

/** The nearest ancestor directory (inclusive) holding a `package.json`. */
export async function findProjectRoot(startDir: string): Promise<string> {
	let dir = startDir;
	for (;;) {
		try {
			await fsp.stat(path.join(dir, "package.json"));
			return dir;
		} catch {
			const parent = path.dirname(dir);
			if (parent === dir) return startDir;
			dir = parent;
		}
	}
}

/** `true` when the project DECLARES `@blokjs/inertia` — the "is this an Inertia app" test. */
export async function projectHasInertia(projectRoot: string): Promise<boolean> {
	try {
		const pkg = JSON.parse(await fsp.readFile(path.join(projectRoot, "package.json"), "utf8")) as Record<
			string,
			Record<string, string> | undefined
		>;
		for (const field of ["dependencies", "devDependencies", "peerDependencies"] as const) {
			if (pkg[field]?.["@blokjs/inertia"] !== undefined) return true;
		}
	} catch {
		/* no package.json, or not JSON — treat as "not an Inertia project" */
	}
	return false;
}

/** The `@blokjs/inertia` the PROJECT resolves — never the CLI's own copy. */
interface InertiaModule {
	getPageRegistry: () => ReadonlyMap<string, { component: string; props: Record<string, PropMeta> }>;
	_resetPageRegistry: () => void;
}

interface PropMeta {
	mode?: string;
	outputSchema?: unknown;
}

async function loadProjectInertia(projectRoot: string): Promise<InertiaModule | null> {
	try {
		const entry = createRequire(path.join(projectRoot, "package.json")).resolve("@blokjs/inertia");
		return (await import(pathToFileURL(entry).href)) as InertiaModule;
	} catch {
		return null;
	}
}

/** The bits of a built workflow this generator reads. */
interface WorkflowConfig {
	name?: string;
	trigger?: { http?: { method?: string; path?: string } };
	steps?: unknown;
}

/** One `page` control step, as the generator reads it. */
interface PageStep {
	component: string;
	props: Record<string, { use?: string }>;
	/** Serializer inputs carried verbatim (`shell`, `head`, `rootId`, `version`, …). */
	inputs: Record<string, unknown>;
}

/** Every `page` control step in a step tree, in declaration order. */
function collectPageSteps(node: unknown, out: PageStep[]): void {
	if (Array.isArray(node)) {
		for (const item of node) collectPageSteps(item, out);
		return;
	}
	if (node === null || typeof node !== "object") return;
	const record = node as Record<string, unknown>;
	const pageStep = record.page as { component?: unknown; props?: unknown; inputs?: unknown } | undefined;
	if (pageStep && typeof pageStep.component === "string") {
		out.push({
			component: pageStep.component,
			props: (pageStep.props ?? {}) as Record<string, { use?: string }>,
			inputs: (pageStep.inputs ?? {}) as Record<string, unknown>,
		});
	}
	for (const value of Object.values(record)) collectPageSteps(value, out);
}

