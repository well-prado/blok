// Importing TypeScript the way TypeScript projects write it
// =============================================================================

/**
 * The `.ts` file a TS-style relative specifier really means, or `undefined`
 * when Node's own resolution is right.
 *
 * A TypeScript project writes `import { nodes } from "../nodes.js"` (or, under
 * `moduleResolution: bundler`, `"../nodes"`) for a file that is `../nodes.ts`
 * on disk. Node resolves the specifier literally, so importing a real workflow
 * module fails with ERR_MODULE_NOT_FOUND on its very first local import —
 * bundlers and `tsc` do this rewrite, and nothing else does.
 */
export function tsFallbackUrl(specifier: string, parentURL: string | undefined): string | undefined {
	if (parentURL === undefined || !/^\.{1,2}\//.test(specifier)) return undefined;
	let target: URL;
	try {
		target = new URL(specifier, parentURL);
	} catch {
		return undefined;
	}
	if (target.protocol !== "file:") return undefined;
	const asPath = fileURLToPath(target);
	if (existsSync(asPath)) return undefined;
	const candidate = asPath.endsWith(".js") ? `${asPath.slice(0, -3)}.ts` : `${asPath}.ts`;
	return existsSync(candidate) ? pathToFileURL(candidate).href : undefined;
}

let hooksRegistered = false;

/**
 * Teach this process to resolve TS-style specifiers, once.
 *
 * `module.registerHooks()` is Node >= 22.15 and synchronous, so it applies to
 * the very next `import()`. On an older Node (or under a bundler-backed test
 * runner, which already does this rewrite) it is simply not needed: the call
 * degrades to a no-op rather than failing the run.
 */
export function enableTsSpecifierResolution(): void {
	if (hooksRegistered) return;
	hooksRegistered = true;
	const registerHooks = (module as { registerHooks?: (hooks: Record<string, unknown>) => void }).registerHooks;
	if (typeof registerHooks !== "function") return;
	registerHooks({
		resolve(
			specifier: string,
			context: { parentURL?: string },
			nextResolve: (s: string, c: { parentURL?: string }) => unknown,
		) {
			const fallback = tsFallbackUrl(specifier, context.parentURL);
			return fallback === undefined ? nextResolve(specifier, context) : { url: fallback, shortCircuit: true };
		},
	});
}

/** Cache-buster: every scan re-imports, so `--watch` never serves a stale module. */
let scanCounter = 0;

/**
 * Explain an import failure. A host that cannot load `.ts` at all is the one
 * failure worth translating: every workflow reports it, and the raw Node
 * message ("Unknown file extension") never mentions the fix.
 */
export function importFailureMessage(err: unknown): string {
	const message = err instanceof Error ? err.message : String(err);
	if (!/Unknown file extension|ERR_UNKNOWN_FILE_EXTENSION/.test(message)) return message;
	return `${message} — this runtime cannot import TypeScript. Run blokctl under Bun, or Node >= 22.18 (type stripping).`;
}

/**
 * Import every workflow module and read the pages + routes out of it.
 *
 * The page registry is process-global, so it is reset before each scan and the
 * modules are re-imported with a fresh query string. ponytail: that leaks the
 * previous module graph in `--watch`; a dev-time generator can afford it, and
 * the alternative is a custom module loader.
 *
 * A `definePage()` that lives OUTSIDE a workflow module (in a shared file) is
 * seen on the first scan only — the shared module stays cached. Declare pages
 * in the workflow module, which is the documented shape.
 */
export async function scanInertiaProject(files: readonly string[], projectRoot: string): Promise<PagesScan | null> {
	const inertia = await loadProjectInertia(projectRoot);
	if (!inertia) return null;
	inertia._resetPageRegistry();
	enableTsSpecifierResolution();

	const token = `blok-gen=${++scanCounter}`;
	const failures: PagesScan["failures"] = [];
	const configs: WorkflowConfig[] = [];

	for (const file of [...files].sort()) {
		try {
			const mod = (await import(`${pathToFileURL(file).href}?${token}`)) as { default?: unknown };
			// `workflow()` is async in the callback DSL: the module's default export
			// is the PROMISE of the built workflow, so a build-time throw surfaces here.
			const built = (await mod.default) as { _config?: WorkflowConfig } | undefined;
			if (built?._config) configs.push(built._config);
		} catch (err) {
			failures.push({ file, message: importFailureMessage(err) });
		}
	}

	// component -> prop key -> node name, for the schemaless-prop warning.
	const nodeNames = new Map<string, Record<string, string>>();
	const routes: ScannedRoute[] = [];
	const shells: PagesScan["shells"] = [];
	for (const config of configs) {
		const pageSteps: PageStep[] = [];
		collectPageSteps(config.steps, pageSteps);
		for (const step of pageSteps) {
			if (typeof step.inputs.shell === "string") shells.push({ component: step.component, shell: step.inputs.shell });
			const names: Record<string, string> = {};
			for (const [key, spec] of Object.entries(step.props)) {
				if (typeof spec?.use === "string") names[key] = spec.use;
			}
			nodeNames.set(step.component, names);
		}
		const http = config.trigger?.http;
		if (!config.name || !http || typeof http.path !== "string") continue;
		routes.push({
			name: config.name,
			method: (http.method ?? "GET").toLowerCase(),
			url: http.path,
			params: [...http.path.matchAll(PARAM)].map((m) => m[1] as string),
			...(pageSteps[0] ? { component: pageSteps[0].component } : {}),
		});
	}
	routes.sort((a, b) => a.name.localeCompare(b.name));

	const schemaless: string[] = [];
	const unsupported: string[] = [];
	const pages: ScannedPage[] = [];
	for (const entry of [...inertia.getPageRegistry().values()]) {
		const props: ScannedProp[] = [];
		for (const [key, meta] of Object.entries(entry.props)) {
			if (meta.outputSchema === undefined) {
				const node = nodeNames.get(entry.component)?.[key];
				schemaless.push(`${entry.component}.${key}${node ? ` (node "${node}")` : ""}`);
			}
			props.push({
				key,
				type: meta.outputSchema === undefined ? "unknown" : zodToTs(meta.outputSchema, "\t\t\t", unsupported),
				optional: LAZY_MODES.has(meta.mode ?? "regular"),
			});
		}
		pages.push({ component: entry.component, props });
	}
	pages.sort((a, b) => a.component.localeCompare(b.component));

	return {
		pages,
		routes,
		failures,
		schemaless,
		unsupported: [...new Set(unsupported)],
		shells,
	};
}

