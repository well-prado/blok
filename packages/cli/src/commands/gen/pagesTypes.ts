export interface PagesSourceOptions {
	/** `withAllErrors` projects get `string[]` per field instead of one message. */
	withAllErrors?: boolean;
}

/** Biome's line width — generated files must come out already formatted. */
const LINE_WIDTH = 120;

/**
 * Render one `Routes` entry: `{ params: { id: string }; method: "get"; … }`,
 * expanded over several lines when the one-liner would exceed Biome's width.
 */
function routeType(route: ScannedRoute, prefixWidth: number): string {
	const parts: string[] = [];
	// A route with NO params must omit the key: `RouteArgs` turns any `params`
	// type into a REQUIRED argument, so `params: {}` would break `route("x")`.
	if (route.params.length > 0) {
		parts.push(`params: { ${route.params.map((p) => `${keyOf(p)}: string`).join("; ")} }`);
	}
	parts.push(`method: ${quote(route.method)}`);
	parts.push(`path: ${quote(route.url)}`);
	if (route.component !== undefined) parts.push(`component: ${quote(route.component)}`);

	const inline = `{ ${parts.join("; ")} }`;
	if (prefixWidth + inline.length + 1 <= LINE_WIDTH) return inline;
	return `{\n${parts.map((p) => `\t\t\t${p};`).join("\n")}\n\t\t}`;
}

/**
 * Build `blok-pages.d.ts`. Pure, so it is unit-testable and the golden files
 * are the whole contract. Returns `null` when there is nothing to declare.
 */
export function buildPagesSource(scan: PagesScan, opts: PagesSourceOptions = {}): string | null {
	if (scan.pages.length === 0 && scan.routes.length === 0) return null;
	const lines: string[] = [
		HEADER,
		'import "@blokjs/inertia-client";',
		'import "@inertiajs/core";',
		"",
		'declare module "@blokjs/inertia-client" {',
	];

	if (scan.pages.length > 0) {
		lines.push("\tinterface Pages {");
		for (const page of scan.pages) {
			if (page.props.length === 0) {
				lines.push(`\t\t${quote(page.component)}: Record<string, never>;`);
				continue;
			}
			lines.push(`\t\t${quote(page.component)}: {`);
			for (const prop of page.props) {
				lines.push(`\t\t\t${keyOf(prop.key)}${prop.optional ? "?" : ""}: ${prop.type};`);
			}
			lines.push("\t\t};");
		}
		lines.push("\t}");
	}

	if (scan.routes.length > 0) {
		if (scan.pages.length > 0) lines.push("");
		lines.push("\tinterface Routes {");
		for (const route of scan.routes) {
			// Biome counts a tab as `indentWidth` (2) columns; two tabs of indent = 4.
			const columns = 4 + quote(route.name).length + 2;
			lines.push(`\t\t${quote(route.name)}: ${routeType(route, columns)};`);
		}
		lines.push("\t}");
	}

	lines.push(
		"}",
		"",
		'declare module "@inertiajs/core" {',
		"\tinterface InertiaConfig {",
		"\t\t// Shared props come from the shared-props registry (#1015), which this",
		"\t\t// project declares none of yet.",
		"\t\tsharedPageProps: Record<never, never>;",
		"\t\t// Flash keys are declared by the flash middleware (#996).",
		"\t\tflashDataType: Record<string, unknown>;",
		`\t\terrorValueType: ${opts.withAllErrors ? "string[]" : "string"};`,
		"\t}",
		"}",
		"",
	);
	return lines.join("\n");
}

/**
 * Build the RUNTIME `blok-routes.ts`. The `Routes` type describes the call
 * signature; this is what actually knows the URL patterns (#997).
 */
export function buildRoutesModuleSource(routes: readonly ScannedRoute[]): string | null {
	if (routes.length === 0) return null;
	const lines: string[] = [
		HEADER,
		'import { registerRoutes } from "@blokjs/inertia-client";',
		"",
		"registerRoutes({",
		...routes.map((route) => {
			const component = route.component === undefined ? "" : `, component: ${quote(route.component)}`;
			return `\t${quote(route.name)}: { url: ${quote(route.url)}, method: ${quote(route.method)}${component} },`;
		}),
		"});",
		"",
	];
	return lines.join("\n");
}

