export interface GeneratePagesOptions {
	/** Directory the workflow files were scanned from. */
	dir: string;
	/** Absolute directory the two files are written into. */
	outDir: string;
	/** Workflow files, absolute. */
	files: readonly string[];
	withAllErrors?: boolean;
	/** Print instead of writing. */
	dryRun?: boolean;
	log?: (line: string) => void;
}

export interface GeneratePagesResult {
	/** Absolute paths written (or that would be, on a dry run). */
	written: string[];
	failures: { file: string; message: string }[];
	/** `false` when the project is not an Inertia app — pages were skipped. */
	scanned: boolean;
}

/**
 * Generate `blok-pages.d.ts` + `blok-routes.ts` for one project.
 *
 * Never throws for a workflow that fails to import: those are returned in
 * `failures` so the caller can report them AND still emit everything else.
 */
export async function generatePages(opts: GeneratePagesOptions): Promise<GeneratePagesResult> {
	const log = opts.log ?? ((line: string) => console.log(line));
	const projectRoot = await findProjectRoot(opts.dir);

	if (!(await projectHasInertia(projectRoot))) {
		log("ℹ️  No @blokjs/inertia in this project — skipping Inertia page types.");
		return { written: [], failures: [], scanned: false };
	}

	const scan = await scanInertiaProject(opts.files, projectRoot);
	if (!scan) {
		log("ℹ️  @blokjs/inertia is declared but not installed — skipping Inertia page types. Run your installer.");
		return { written: [], failures: [], scanned: false };
	}

	const pagesSource = buildPagesSource(scan, { withAllErrors: opts.withAllErrors });
	const routesSource = buildRoutesModuleSource(scan.routes);
	const written: string[] = [];

	for (const [name, source] of [
		["blok-pages.d.ts", pagesSource],
		["blok-routes.ts", routesSource],
	] as const) {
		if (source === null) continue;
		const file = path.join(opts.outDir, name);
		if (opts.dryRun === true) {
			log(`— dry run — would write ${file}:\n`);
			log(source);
		} else {
			await fsp.mkdir(opts.outDir, { recursive: true });
			await fsp.writeFile(file, source, "utf8");
		}
		written.push(file);
	}

	if (pagesSource === null) {
		log("ℹ️  No `definePage()` pages and no HTTP routes found — no Inertia types to write.");
	} else if (opts.dryRun !== true) {
		log(`✅ Wrote ${written.join(", ")} (${scan.pages.length} page(s), ${scan.routes.length} route(s)).`);
	}

	if (scan.schemaless.length > 0) {
		log(
			`⚠️  ${scan.schemaless.length} prop(s) have no Zod output schema and were typed \`unknown\`: ${scan.schemaless.join(", ")}.`,
		);
	}
	if (scan.unsupported.length > 0) {
		log(`⚠️  Zod type(s) this generator does not model were typed \`unknown\`: ${scan.unsupported.join(", ")}.`);
	}
	for (const failure of scan.failures) {
		log(`❌ ${failure.file}: ${failure.message}`);
	}

	return { written, failures: scan.failures, scanned: true };
}
