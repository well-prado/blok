/** One page prop, already rendered as TypeScript. */
export interface ScannedProp {
	key: string;
	type: string;
	/** `optional` / `defer` props are absent unless the visit asked for them. */
	optional: boolean;
}

export interface ScannedPage {
	component: string;
	props: ScannedProp[];
}

export interface ScannedRoute {
	name: string;
	/** Inertia's lowercase method (`"get"`), per #997. */
	method: string;
	url: string;
	params: string[];
	component?: string;
}

export interface PagesScan {
	pages: ScannedPage[];
	routes: ScannedRoute[];
	/** Workflow modules that threw on import: reported, and the run exits non-zero. */
	failures: { file: string; message: string }[];
	/** Props whose node carries no Zod output schema — emitted as `unknown`. */
	schemaless: string[];
	/** Zod types this converter does not model — emitted as `unknown`. */
	unsupported: string[];
	/**
	 * Custom HTML shells passed to `render()` (#1019) — what `blokctl inertia
	 * doctor` checks for the `<!--blok:app-->` / `<!--blok:head-->` markers.
	 * Empty when every page uses the built-in shell.
	 */
	shells: { component: string; shell: string }[];
}

// =============================================================================
// Loading the project
