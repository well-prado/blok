/**
 * `blokctl gen app-types` — the Inertia half (#998).
 *
 * Alongside `blok-app.d.ts` (the typed `BlokApp` index for `@blokjs/client`),
 * the same run emits the two files a Blok SPA needs:
 *
 * - `blok-pages.d.ts` — types only. Augments `@blokjs/inertia-client`'s `Pages`
 *   and `Routes`, and Inertia's own `InertiaConfig`, so the stock hooks
 *   (`usePage`, `useForm`, …) are typed without a Blok-specific wrapper.
 * - `blok-routes.ts` — RUNTIME. One `registerRoutes({ … })` call the SPA entry
 *   imports at boot, because the `Routes` TYPE cannot build a URL (#997).
 *
 * Unlike the `blok-app.d.ts` scanner, this one EXECUTES the project's workflow
 * modules: prop types come from the Zod output schemas that `definePage()`
 * records in `getPageRegistry()`, and those only exist at runtime. Everything
 * else (route method/path/component) is read off the built workflow object, so
 * there is no second, drifting parser of the authoring surface.
 */

import { existsSync, promises as fsp } from "node:fs";
import module, { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** Header line on every generated file — names the generator and warns off edits. */
const HEADER = "// AUTO-GENERATED by `blokctl gen app-types` — do not edit by hand.";

/** Same param syntax `@blokjs/inertia-client`'s `route()` interpolates. */
const PARAM = /:([A-Za-z_][A-Za-z0-9_]*)/g;

// =============================================================================
// Zod → TypeScript
// =============================================================================

/** What a Zod schema looks like from the outside, without importing zod itself. */
interface ZodDef {
	typeName?: string;
	[key: string]: unknown;
}

function defOf(schema: unknown): ZodDef | undefined {
	if (schema === null || typeof schema !== "object") return undefined;
	const def = (schema as { _def?: unknown })._def;
	return def !== null && typeof def === "object" ? (def as ZodDef) : undefined;
}

function quote(value: string): string {
	return JSON.stringify(value);
}

/** A TS object key that does not need quoting. */
function keyOf(name: string): string {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : quote(name);
}

/** Unwrap the wrappers that do not change the SHAPE of the value. */
function innerOf(def: ZodDef): unknown {
	return def.innerType ?? def.schema ?? def.type ?? (def.out as unknown);
}

/**
 * Render a Zod schema as a TypeScript type.
 *
 * Deliberately small (#998): object / array / optional / nullable / union /
 * discriminated union / intersection / literal / enum / record / tuple /
 * primitives, plus the transparent wrappers (`default`, `catch`, `brand`,
 * `readonly`, `effects`, `pipeline`). Anything else falls back to `unknown` and
 * is reported by name, so a gap is visible instead of silently wrong.
 *
 * `z.date()` renders as `string`: page props cross the wire as JSON.
 */
export function zodToTs(schema: unknown, indent = "\t\t", unsupported: string[] = []): string {
	const def = defOf(schema);
	if (!def || typeof def.typeName !== "string") {
		unsupported.push("(not a zod schema)");
		return "unknown";
	}
	const next = `${indent}\t`;
	switch (def.typeName) {
		case "ZodString":
			return "string";
		case "ZodNumber":
			return "number";
		case "ZodBigInt":
			return "bigint";
		case "ZodBoolean":
			return "boolean";
		case "ZodDate":
			return "string";
		case "ZodNull":
			return "null";
		case "ZodUndefined":
			return "undefined";
		case "ZodVoid":
			return "void";
		case "ZodNever":
			return "never";
		case "ZodAny":
		case "ZodUnknown":
			return "unknown";
		case "ZodLiteral":
			return typeof def.value === "string" ? quote(def.value) : String(def.value);
		case "ZodEnum":
			return (def.values as string[]).map(quote).join(" | ");
		case "ZodArray":
			return `Array<${zodToTs(def.type, indent, unsupported)}>`;
		case "ZodOptional":
			return `${zodToTs(innerOf(def), indent, unsupported)} | undefined`;
		case "ZodNullable":
			return `${zodToTs(innerOf(def), indent, unsupported)} | null`;
		case "ZodDefault":
		case "ZodCatch":
		case "ZodBranded":
		case "ZodReadonly":
		case "ZodEffects":
			return zodToTs(innerOf(def), indent, unsupported);
		case "ZodPipeline":
			return zodToTs(def.out, indent, unsupported);
		case "ZodUnion":
		case "ZodDiscriminatedUnion": {
			const options = def.options as unknown[] | Map<unknown, unknown>;
			const list = Array.isArray(options) ? options : [...options.values()];
			return list.map((o) => zodToTs(o, indent, unsupported)).join(" | ");
		}
		case "ZodIntersection":
			return `${zodToTs(def.left, indent, unsupported)} & ${zodToTs(def.right, indent, unsupported)}`;
		case "ZodTuple": {
			const items = (def.items as unknown[]).map((i) => zodToTs(i, indent, unsupported));
			const rest = def.rest ? `, ...Array<${zodToTs(def.rest, indent, unsupported)}>` : "";
			return `[${items.join(", ")}${rest}]`;
		}
		case "ZodRecord":
			return `Record<${zodToTs(def.keyType, indent, unsupported)}, ${zodToTs(def.valueType, indent, unsupported)}>`;
		case "ZodObject": {
			const shape = (def.shape as () => Record<string, unknown>)();
			const keys = Object.keys(shape);
			if (keys.length === 0) return "Record<string, never>";
			const lines = keys.map((key) => {
				const value = shape[key];
				const valueDef = defOf(value);
				// `a: z.string().optional()` is an OPTIONAL KEY, not a `| undefined` value.
				const isOptional = valueDef?.typeName === "ZodOptional";
				const rendered = zodToTs(isOptional ? innerOf(valueDef as ZodDef) : value, next, unsupported);
				return `${next}${keyOf(key)}${isOptional ? "?" : ""}: ${rendered};`;
			});
			return `{\n${lines.join("\n")}\n${indent}}`;
		}
		default:
			unsupported.push(def.typeName);
			return "unknown";
	}
}

// =============================================================================
// What a scan produces
